#!/usr/bin/env python3
"""Build a hand-off kit for rebuilding the CND templates in Canva.

    .venv/bin/python graphics/build-canva-kit.py

Writes graphics/out/canva-kit/ containing:

    frames/     frame-only PNGs at 2x, with a transparent content window
    assets/     the vector logo set and the two font families
    BUILD.md    exact positions, sizes, colours and tracking

Why this exists
---------------
Canva's API cannot build these layouts. It has no operation to create a text
element, and it explicitly does not support setting font family — so a design
assembled through the API would be neither correctly laid out nor correctly
typeset. The final "publish as Brand Template" step is UI-only too.

So the templates get built once by hand in Canva, and this turns that from a
design job into a data-entry job: the frame furniture arrives as artwork that
nobody has to redraw, and every number comes out of geometry.json rather than
somebody's eye.

The numbers here are the same ones the renderer uses, so a Canva rebuild and a
rendered PNG stay in agreement.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KIT = ROOT / "graphics" / "out" / "canva-kit"

# Category -> the template that draws it.
TEMPLATE_FOR = {
    "speaker-highlights": "speaker-highlight",
    "sponsor-highlights": "sponsor-highlight",
    "schedule-announcements": "schedule-announcement",
    "CFP-notifications": "cfp-notification",
    "clean": "clean",
}

ASSETS = [
    ("cnd-lockup-cream.svg", "wordmark for navy grounds"),
    ("cnd-lockup-navy.svg", "wordmark for sand/white grounds"),
    ("cnd-mark.svg", "the flag mark alone"),
    ("cnd-hexagons.svg", "4-hexagon cluster (built to darken sand — not for navy)"),
    ("cnd-hexagons-solid.svg", "same cluster baked opaque, safe on any ground"),
    ("cnd-shape.svg", "logo silhouette, for cropping portraits and tiles"),
    ("cnd-lockup-cover.svg", "fused wordmark+mark, as used on the cover"),
]

FONTS = ["SpaceGrotesk-Medium.ttf", "SpaceGrotesk-Bold.ttf", "Inter-Variable.ttf"]

COLOR_ROLES = {
    "navy": "primary ground; display text on light",
    "red": "tabs, rules, eyebrows, outline strokes",
    "sand": "warm alternate ground",
    "bone": "slide ground (decks)",
    "white": "cards, text on navy",
    "rose": "hexagon cluster / accent",
    "peach": "hexagon cluster / accent",
    "slate": "muted accent",
    "ink-muted": "body copy on light",
}

FRIENDLY = {
    "NAME LASTNAME": "Speaker name",
    "Titel Lorem ipsum": "Role / org",
    "Highlight Lorem ipsum dolores Lorem Ipsum": "Statement",
}


def render_frames() -> int:
    (KIT / "frames").mkdir(parents=True, exist_ok=True)
    made = 0
    for category, template in TEMPLATE_FOR.items():
        for variant in ("1", "2", "3"):
            out = KIT / "frames" / f"{category}-v{variant}-frame@2x.png"
            proc = subprocess.run(
                [
                    "node", str(ROOT / "graphics" / "render.mjs"), template,
                    "--category", category, "--variant", variant,
                    "--frame", "--scale", "2", "--out", str(out),
                ],
                capture_output=True, text=True,
            )
            if proc.returncode == 0:
                made += 1
            else:
                print(f"  ! {category} v{variant}: {proc.stderr.strip()[:80]}")
    return made


def copy_assets() -> None:
    dest = KIT / "assets"
    dest.mkdir(parents=True, exist_ok=True)
    for name, _ in ASSETS:
        src = ROOT / "brand" / "logo" / name
        if src.exists():
            shutil.copy2(src, dest / name)
    for name in FONTS:
        src = ROOT / "brand" / "fonts" / name
        if src.exists():
            shutil.copy2(src, dest / name)


def build_sheet(geometry: dict, tokens: dict) -> str:
    out: list[str] = []
    w = out.append

    w("# Building the CND 2026 templates in Canva\n")
    w("Generated by `graphics/build-canva-kit.py` from `brand/geometry.json` —")
    w("these are the designer's measured numbers, not estimates. Canvas is")
    w("**1080 × 1350** (LinkedIn 4:5).\n")

    w("## 1. Brand kit — do this first\n")
    w("The existing kit is **KCD Denmark 2024**, the pre-rename branding. Create")
    w("a new kit called **Cloud Native Denmark 2026** and leave the old one")
    w("alone.\n")
    w("| Token | Hex | Use |")
    w("|---|---|---|")
    for key, value in tokens["color"].items():
        w(f"| {key} | `{value}` | {COLOR_ROLES.get(key, '')} |")
    w("\nUpload the three fonts in `assets/`.\n")
    w("> Social graphics are set **entirely in Space Grotesk Medium, uppercase,")
    w("> tracking 0.02em**. No Bold, no Inter — verified against every text layer")
    w("> in her PSDs. Bold is for deck display type only.\n")

    w("## 2. Frame — use the PNG, don't redraw it\n")
    w("`frames/<category>-v<n>-frame@2x.png` is the frame furniture at 2160×2700")
    w("with a **transparent content window**. Place it as the top layer and lock")
    w("it; photos go underneath, text on top. The tab, footer band, lockup and")
    w("outline year then stay pixel-exact without anyone rebuilding them.\n")
    w("**v1** navy + full-bleed photo · **v2** navy + white card · **v3** sand +")
    w("white card.\n")

    w("## 3. Text — exact positions\n")
    w("These are **baselines**, where the letters sit. Canva positions a text box")
    w("by its top edge, so subtract roughly 0.7 × font size — or place it against")
    w("the frame PNG by eye, which is what the frame is there for.\n")
    for variant, label in [
        ("1", "v1 — over a full-bleed photo"),
        ("2", "v2 / v3 — inside the white card"),
    ]:
        w(f"### {label}\n")
        w("| Element | x | baseline y | size | colour | tracking |")
        w("|---|---|---|---|---|---|")
        for name, spec in geometry["content"][variant].items():
            run = spec["runs"][0]
            lead = (
                f", leading {spec['leading_derived_px']}px"
                if spec["leading_derived_px"]
                else ""
            )
            w(
                f"| {FRIENDLY.get(name, name)} | {spec['x']} | {spec['baseline']} "
                f"| {run['size_px']}px | `{run['color']}` | {run['tracking_em']}em{lead} |"
            )
        w("")

    frames = geometry["frames"]["speaker-highlights"]
    w("### Tab label — only needed if you rebuild the tab\n")
    w("| Variant | centre x | baseline y | size | leading | rotation |")
    w("|---|---|---|---|---|---|")
    for variant in "123":
        label = frames[variant]["label"]
        run = label["runs"][0]
        w(
            f"| v{variant} | {round(label['x'] + label['w'] / 2, 1)} | "
            f"{label['baseline']} | {run['size_px']}px | "
            f"{label['leading_derived_px']}px | {label['rotation']}° |"
        )
    w("")

    overlays = geometry["overlays"]["speaker-highlights"]
    w("## 4. Frame geometry, for a native rebuild\n")
    w("| | v1 | v2 | v3 |")
    w("|---|---|---|---|")

    def row(label: str, fn) -> None:
        w(f"| {label} | " + " | ".join(fn(overlays[v]) for v in "123") + " |")

    row("ground", lambda d: f"`{d['ground']}`")
    row(
        "content window",
        lambda d: f"{d['content']['x']},{d['content']['y']} "
        f"{d['content']['w']}×{d['content']['h']}",
    )
    row("corner radius", lambda d: f"{d['content']['r']}px")
    row(
        "red rule",
        lambda d: f"y {d['rule']['y']}, {d['rule']['h']}px" if "rule" in d else "—",
    )
    row(
        "lockup",
        lambda d: f"{d['lockup']['x']},{d['lockup']['y']} "
        f"{d['lockup']['w']}×{d['lockup']['h']}",
    )
    row(
        "flag mark",
        lambda d: f"{d['mark']['x']},{d['mark']['y']} "
        f"{d['mark']['w']}×{d['mark']['h']}",
    )

    year = frames["2"]["year"]
    run = year["runs"][0]
    w(
        f"\nYear `2026`: x {year['x']}, baseline {year['baseline']}, "
        f"{run['size_px']}px, tracking {run['tracking_em']}em."
    )
    w("**It is not a red glyph.** The fill is the ground colour and the *stroke*")
    w("is red at 3px — same mechanism as `DENMARK.` in the lockup. That is why it")
    w("separates correctly for print. In Canva, use the supplied lockup SVG,")
    w("which already carries it.\n")

    portrait = tokens["portrait"]
    card = overlays["2"]["content"]
    side = round(card["h"] * portrait["sideOfCardHeight"])
    cx = round(card["x"] + card["w"] * portrait["centreXOfCardWidth"])
    cy = round(card["y"] + card["h"] * portrait["centreYOfCardHeight"])
    w("## 5. Portrait\n")
    w(f"Circle, **{side}px** across, centred at **({cx}, {cy})** — matching her")
    w("own composed example. `assets/cnd-shape.svg` is the logo silhouette if you")
    w("want the mark-shaped crop instead; it is her mark's outline, verified at")
    w("0.9977 IoU against it.\n")

    w("## 6. Assets\n")
    w("| File | What |")
    w("|---|---|")
    for name, description in ASSETS:
        w(f"| `assets/{name}` | {description} |")
    w("\nAll real vector, extracted from her PSD's embedded smart objects.\n")

    w("## 7. Publish as Brand Templates\n")
    w("Save each finished design, then **Share → Brand Template**. There is no")
    w("API for that step. Once the templates exist and their text elements carry")
    w("autofill labels, designs can be created and populated programmatically —")
    w("and the labels themselves can be attached through the API.\n")

    return "\n".join(out) + "\n"


def main() -> int:
    geometry = json.loads((ROOT / "brand" / "geometry.json").read_text())
    tokens = json.loads((ROOT / "brand" / "tokens.json").read_text())

    KIT.mkdir(parents=True, exist_ok=True)
    print("rendering frames ...")
    made = render_frames()
    print("copying assets ...")
    copy_assets()
    (KIT / "BUILD.md").write_text(build_sheet(geometry, tokens))

    print(f"\nwrote {KIT.relative_to(ROOT)}")
    print(f"  {made} frame PNGs at 2x")
    print(f"  {len(ASSETS)} vector assets, {len(FONTS)} fonts")
    print("  BUILD.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
