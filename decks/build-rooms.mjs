#!/usr/bin/env node
/**
 * Build the door signs for the venue's screens from content/2026-rooms.json.
 *
 *   node decks/build-rooms.mjs              every room, HTML and PDF
 *   node decks/build-rooms.mjs Hamlet       just these (by file name)
 *   node decks/build-rooms.mjs --pptx       then PowerPoint as well
 *
 * Writes graphics/out/rooms/<file>.html, .pdf and (with --pptx) .pptx. The
 * venue asked for PDF; the PPTX is the same page with its text laid back on
 * top as editable text boxes, made by decks/breaks-to-pptx.py.
 *
 * One 16:9 slide per room, in the stage look: navy, the honeycomb on the
 * right, lockup top left, the room's purpose as display type.
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "graphics", "out", "rooms");

const args = process.argv.slice(2);
const pptx = args.includes("--pptx");
const only = new Set(args.filter((a) => !a.startsWith("--")));

const { rooms } = JSON.parse(readFileSync(join(ROOT, "content", "2026-rooms.json"), "utf8"));
const todo = rooms.filter((r) => !only.size || only.has(r.file));

const esc = (s) =>
  String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const up = (p) => relative(OUT, join(ROOT, p));

const page = (r) => `<!doctype html>
<!-- GENERATED by decks/build-rooms.mjs from content/2026-rooms.json — do not edit. -->
<html lang="en">
<head>
<meta charset="utf-8">
<title>${esc(r.sign.replace(/\|/g, " "))} · Cloud Native Denmark 2026</title>
<link rel="stylesheet" href="${up("brand/tokens.css")}">
<link rel="stylesheet" href="${up("decks/shared/cnd-deck.css")}">
<style>
  .slide[data-layout="room"] .pad {
    display: flex;
    flex-direction: column;
    justify-content: space-between;
  }
  .slide[data-layout="room"] .display {
    font-size: 220px;
    line-height: 0.92;
  }
  .slide[data-layout="room"] .eyebrow {
    font-size: 44px;
    margin-bottom: 36px;
  }
  .slide[data-layout="room"] .foot {
    font-family: var(--cnd-font-display);
    font-weight: 500;
    font-size: 30px;
    letter-spacing: var(--cnd-track-eyebrow);
    text-transform: uppercase;
    color: var(--muted);
    margin: 0;
  }
</style>
</head>
<body class="deck" data-deck-title="${esc(r.file)}">

<section class="slide" data-layout="room" data-field="right">
  <div class="pad">
    <div class="lockup" style="--w: 420px">
      <img class="wordmark" src="${up("brand/logo/cnd-lockup-cream.svg")}" alt="Cloud Native Denmark">
      <img class="mark" src="${up("brand/logo/cnd-mark.svg")}" alt="">
    </div>
    <div>
      ${r.room ? `<p class="eyebrow">${esc(r.room)}</p>` : ""}
      <h1 class="display">${r.sign.split("|").map(esc).join("<br>")}</h1>
    </div>
    <p class="foot">19–20 Nov 2026 · cloudnativedenmark.dk</p>
  </div>
</section>

<script src="${up("stage/show.data.js")}"></script>
<script src="${up("decks/shared/deck.js")}"></script>
</body>
</html>
`;

function findChrome() {
  const c = [
    process.env.CHROME_BIN,
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    "/usr/bin/google-chrome",
    "/usr/bin/google-chrome-stable",
    "/usr/bin/chromium",
  ].filter(Boolean);
  const hit = c.find((p) => existsSync(p));
  if (!hit) throw new Error("Chrome not found; set CHROME_BIN");
  return hit;
}

mkdirSync(OUT, { recursive: true });
const chrome = findChrome();
for (const r of todo) {
  const html = join(OUT, `${r.file}.html`);
  writeFileSync(html, page(r));
  execFileSync(
    chrome,
    [
      "--headless",
      "--disable-gpu",
      "--no-pdf-header-footer",
      "--virtual-time-budget=10000",
      `--print-to-pdf=${join(OUT, `${r.file}.pdf`)}`,
      `file://${html}`,
    ],
    { stdio: ["ignore", "ignore", "ignore"] },
  );
  console.log(`${r.file.padEnd(18)} ${r.sign.replace(/\|/g, " ")}`);
}

if (pptx) {
  const venv = join(ROOT, ".venv", "bin", "python");
  const python = existsSync(venv) ? venv : "python3";
  execFileSync(
    python,
    [join(ROOT, "decks", "breaks-to-pptx.py"), "--src", OUT, "--out", OUT, ...todo.map((r) => r.file)],
    { stdio: "inherit" },
  );
}
