#!/usr/bin/env python3
"""Build the deck maps: shared/denmark.js and shared/nordics.js.

    curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_10m_admin_0_countries.geojson
    python3 decks/shared/build-maps.py ne_10m_admin_0_countries.geojson

Source: Natural Earth 1:10m admin-0 countries v5.1.2, public domain. The
geojson is 13 MB, so it is not kept in the repo; the outputs are.

Each output sets a window global the deck runtime reads: a viewBox, one land
path, and pins as [x, y, side], where side says which way the label goes
(l, r, t, b). Sides are chosen by hand per city so neighbours do not
collide, which is why they live here rather than being computed.
"""

import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).parent


def load(path, codes):
    data = json.loads(Path(path).read_text())
    return {
        f["properties"]["ADM0_A3"]: f["geometry"]
        for f in data["features"]
        if f["properties"]["ADM0_A3"] in codes
    }


def rings_of(geom):
    polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
    return [poly[0] for poly in polys]


def build(name, var, rings, cities, project, simplify, header):
    pts = [project(*p) for r in rings for p in r]
    minx, maxx = min(p[0] for p in pts), max(p[0] for p in pts)
    miny, maxy = min(p[1] for p in pts), max(p[1] for p in pts)
    W = 1000
    s = W / (maxx - minx)
    H = round((maxy - miny) * s)

    def tf(lon, lat):
        x, y = project(lon, lat)
        return (x - minx) * s, (y - miny) * s

    out = []
    for r in rings:
        p = [tf(*q) for q in r]
        keep = [p[0]]
        for q in p[1:]:
            if math.dist(q, keep[-1]) >= simplify:
                keep.append(q)
        if len(keep) < 4:
            continue
        out.append("M" + " ".join(f"{x:.1f} {y:.1f}" for x, y in keep) + "Z")
    pins = {n: [round(v, 1) for v in tf(lon, lat)] + [side] for n, (lon, lat, side) in cities.items()}
    js = (
        f"/* GENERATED by decks/shared/build-maps.py — do not edit.\n *\n{header}\n */\n"
        f"window.{var} = {{\n"
        f'  viewBox: "0 0 {W} {H}",\n'
        f"  pins: {json.dumps(pins, ensure_ascii=False)},\n"
        f'  d: "{"".join(out)}",\n'
        f"}};\n"
    )
    (HERE / name).write_text(js)
    print(f"{name}: viewBox 0 0 {W} {H}, {len(out)} rings")


def main(path):
    geoms = load(path, {"DNK", "SWE", "NOR", "FIN"})

    # Denmark: equirectangular, longitude scaled by cos(56°). Bornholm is
    # moved 1.4° west so the mainland can be drawn larger, the way Danish
    # maps usually inset it.
    K = math.cos(math.radians(56.0))

    def dk_rings():
        for r in rings_of(geoms["DNK"]):
            shift = -1.4 if min(p[0] for p in r) > 14.5 else 0
            yield [(lon + shift, lat) for lon, lat in r]

    build(
        "denmark.js",
        "CND_DENMARK",
        list(dk_rings()),
        {
            "Aalborg": (9.9187, 57.0488, "r"),
            "Aarhus": (10.2039, 56.1629, "r"),
            "Copenhagen": (12.5683, 55.6761, "t"),
        },
        lambda lon, lat: (lon * K, -lat),
        1.4,
        " * Denmark with the three community cities. Natural Earth 1:10m, DNK.\n"
        " * Equirectangular, longitude × cos(56°); Bornholm moved 1.4° west.",
    )

    # The Nordics: Lambert azimuthal equal-area centred on 15°E 63°N, so
    # Finland keeps its shape instead of stretching the way a
    # flat lon/lat map does this far north. Only rings inside the Nordic box
    # are kept: Norway's feature also carries Svalbard, Jan Mayen and Bouvet
    # Island in the South Atlantic, which would stretch the map for no city.
    lon0, lat0 = math.radians(15), math.radians(63)

    def laea(lon, lat):
        l, p = math.radians(lon) - lon0, math.radians(lat)
        k = math.sqrt(2 / (1 + math.sin(lat0) * math.sin(p) + math.cos(lat0) * math.cos(p) * math.cos(l)))
        x = k * math.cos(p) * math.sin(l)
        y = k * (math.cos(lat0) * math.sin(p) - math.sin(lat0) * math.cos(p) * math.cos(l))
        return x, -y

    rings = [
        r
        for code in ("NOR", "SWE", "FIN", "DNK")
        for r in rings_of(geoms[code])
        if 54 < min(p[1] for p in r) and max(p[1] for p in r) < 71.5 and -25 < min(p[0] for p in r) and max(p[0] for p in r) < 32
        and not (code == "NOR" and min(p[0] for p in r) < -5)
    ]
    build(
        "nordics.js",
        "CND_NORDICS",
        rings,
        {
            "Aalborg": (9.9187, 57.0488, "l"),
            "Aarhus": (10.2039, 56.1629, "l"),
            "Copenhagen": (12.5683, 55.6761, "r"),
            "Göteborg": (11.9746, 57.7089, "r"),
            "Oslo": (10.7522, 59.9139, "t"),
            "Bergen": (5.3221, 60.3913, "l"),
            "Stavanger": (5.7331, 58.9700, "l"),
            "Stockholm": (18.0686, 59.3293, "r"),
            "Umeå": (20.2630, 63.8258, "r"),
            "Turku": (22.2666, 60.4518, "b"),
            "Tampere": (23.7610, 61.4978, "r"),
            "Helsinki": (24.9384, 60.1699, "r"),
        },
        laea,
        1.2,
        " * Denmark, Norway, Sweden and Finland with the twelve Cloud\n"
        " * Native Nordics cities. Natural Earth 1:10m. Lambert azimuthal\n"
        " * equal-area centred on 15°E 63°N; Norway's far\n"
        " * islands left out.",
    )


if __name__ == "__main__":
    main(sys.argv[1])
