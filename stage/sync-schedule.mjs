#!/usr/bin/env node
/**
 * Snapshot the final schedule from Sessionize into content/2026-schedule.json.
 *
 *   node stage/sync-schedule.mjs
 *
 * The schedule lives in Sessionize (the same feed cloudnativedenmark.dk reads).
 * The show runs from the snapshot, not the API, so the wall never depends on
 * venue Wi-Fi; re-run this when the programme changes and review the diff.
 *
 * Speakers without a portrait in assets/speakers/ get their Sessionize photo
 * downloaded as assets/speakers/<first_last>.jpg, the naming the rest use.
 */

import { existsSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const EVENT = "6dzu68z1";
const API = `https://sessionize.com/api/v2/${EVENT}/view`;

// The Grid view, because it is the only one that carries the service sessions
// (breaks, lunch, the sponsor pitches); speakers' taglines and photos come
// from the Speakers view.
async function get(view) {
  const res = await fetch(`${API}/${view}`);
  if (!res.ok) {
    console.error(`Sessionize answered ${res.status} for ${API}/${view}`);
    process.exit(1);
  }
  return res.json();
}
const grid = await get("Grid");
const speakers = new Map((await get("Speakers")).map((s) => [s.id, s]));
const dates = grid.map((d) => d.date.slice(0, 10)).sort();
const slots = grid.flatMap((d) => d.timeSlots.flatMap((ts) => ts.rooms.map((r) => ({ ...r.session, room: r.name }))));

/** "Kārlis Akots Gribulis" → "karlis_akots_gribulis", as assets/speakers/ names them. */
const fileStem = (name) =>
  name
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/ø/g, "o")
    .replace(/æ/g, "ae")
    .replace(/å/g, "a")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "");

function portraitFor(name) {
  for (const ext of ["jpg", "png"]) {
    const p = `assets/speakers/${fileStem(name)}.${ext}`;
    if (existsSync(join(ROOT, p))) return p;
  }
  return null;
}

const downloads = new Map(); // portrait path → photo URL, once per speaker
const sessions = slots
  .sort((a, b) => a.startsAt.localeCompare(b.startsAt) || a.room.localeCompare(b.room))
  .map((s) => ({
    id: String(s.id),
    title: s.title,
    room: s.room,
    day: String(dates.indexOf(s.startsAt.slice(0, 10)) + 1),
    start: s.startsAt.slice(11, 16),
    end: s.endsAt.slice(11, 16),
    service: s.isServiceSession,
    speakers: s.speakers.map(({ id }) => {
      const sp = speakers.get(id);
      let portrait = portraitFor(sp.fullName);
      if (!portrait && sp.profilePicture) {
        portrait = `assets/speakers/${fileStem(sp.fullName)}.jpg`;
        downloads.set(portrait, sp.profilePicture);
      }
      return { name: sp.fullName, tagLine: sp.tagLine ?? "", portrait };
    }),
  }));

for (const [path, url] of downloads) {
  const r = await fetch(url);
  if (!r.ok) {
    console.error(`  could not download ${url}: ${r.status}`);
    continue;
  }
  writeFileSync(join(ROOT, path), Buffer.from(await r.arrayBuffer()));
  console.log(`  downloaded ${path}`);
}

const out = join(ROOT, "content", "2026-schedule.json");
writeFileSync(
  out,
  JSON.stringify(
    {
      $comment:
        "GENERATED by stage/sync-schedule.mjs from Sessionize — do not edit; fix it in Sessionize and re-run. Times are local (Copenhagen). `day` is 1 or 2.",
      source: `${API}/Grid`,
      dates,
      sessions,
    },
    null,
    2,
  ) + "\n",
);
console.log(`content/2026-schedule.json  ${sessions.length} sessions over ${dates.length} days`);
